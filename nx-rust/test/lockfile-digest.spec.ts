// Checks the digest of DES-LOCKFILE-HASHING on lockfiles written here, the
// folder names of the digests, and how the preTasksExecution hook reads a
// command that excludes task dependencies. lockfile-keys.spec.ts checks the
// keys that the digests give with Nx's own hasher, on lockfiles that cargo
// writes.

const crates = "registry+https://github.com/rust-lang/crates.io-index";
const member = { name: "app", version: "0.1.0" };

/** A `[[package]]` table. */
function entry(fields: {
  name: string;
  version: string;
  source?: string;
  checksum?: string;
  replace?: string;
  dependencies?: string[];
}): string {
  return [
    "[[package]]",
    `name = "${fields.name}"`,
    `version = "${fields.version}"`,
    ...(fields.source === undefined ? [] : [`source = "${fields.source}"`]),
    ...(fields.checksum === undefined ? [] : [`checksum = "${fields.checksum}"`]),
    ...(fields.replace === undefined ? [] : [`replace = "${fields.replace}"`]),
    ...(fields.dependencies === undefined
      ? []
      : [`dependencies = [${fields.dependencies.map((d) => JSON.stringify(d)).join(", ")}]`]),
    "",
  ].join("\n");
}

/** A lockfile of the fourth format with these entries. */
function lockfile(...entries: string[]): string {
  return ["# This file is automatically @generated by Cargo.", "version = 4", "", ...entries].join(
    "\n",
  );
}

function digest(text: string, of = member): string {
  return memberDigest(parseLockfile(text), of);
}

const base = [
  entry({ name: "app", version: "0.1.0", dependencies: ["itoa", "lib"] }),
  entry({ name: "lib", version: "0.1.0", dependencies: ["ryu"] }),
  entry({ name: "itoa", version: "1.0.0", source: crates, checksum: "a".repeat(64) }),
  entry({ name: "ryu", version: "1.0.0", source: crates, checksum: "b".repeat(64) }),
  entry({ name: "other", version: "1.0.0", source: crates, checksum: "c".repeat(64) }),
];

describe("a member's digest", () => {
  it("is the SHA-256 of one tab-joined line per reachable entry, in byte order", () => {
    const lines = [
      ["app", "0.1.0", "", "", "", "itoa", "lib"],
      ["itoa", "1.0.0", crates, "a".repeat(64), ""],
      ["lib", "0.1.0", "", "", "", "ryu"],
      ["ryu", "1.0.0", crates, "b".repeat(64), ""],
    ].map((fields) => `${fields.join("\t")}\n`);

    expect(digest(lockfile(...base))).toBe(
      createHash("sha256").update(lines.join(""), "utf8").digest("hex"),
    );
  });

  it("changes with the version, the checksum or the source of an entry the member reaches, also through a path package", () => {
    const original = digest(lockfile(...base));
    for (const changed of [
      base.map((text) => text.replace('version = "1.0.0"\nsource', 'version = "1.0.1"\nsource')),
      base.map((text) => text.replace("b".repeat(64), "d".repeat(64))),
      base.map((text) =>
        text.includes('name = "ryu"')
          ? text.replace(crates, "git+https://example.com/ryu#1234")
          : text,
      ),
    ]) {
      expect(digest(lockfile(...changed))).not.toBe(original);
    }
  });

  it("does not change with an entry that the member does not reach, nor with the order of entries and dependency strings", () => {
    const original = digest(lockfile(...base));
    const unrelated = base.map((text) => text.replace("c".repeat(64), "e".repeat(64)));
    const reordered = [...base]
      .reverse()
      .map((text) => text.replace('["itoa", "lib"]', '["lib", "itoa"]'));

    expect(digest(lockfile(...unrelated))).toBe(original);
    expect(digest(lockfile(...reordered))).toBe(original);
  });

  it("counts the dependency strings, so that the same packages with another edge differ", () => {
    // wrapper uses zzlib 2 in one lockfile and zzlib 1 in the other.
    const zz = [
      entry({ name: "zzlib", version: "1.0.0", source: crates, checksum: "1".repeat(64) }),
      entry({ name: "zzlib", version: "2.0.0", source: crates, checksum: "2".repeat(64) }),
    ];
    const withEdge = (version: string) =>
      lockfile(
        entry({
          name: "app",
          version: "0.1.0",
          dependencies: ["wrapper", "zzlib 1.0.0", "zzlib 2.0.0"],
        }),
        entry({
          name: "wrapper",
          version: "1.0.0",
          source: crates,
          dependencies: [`zzlib ${version}`],
        }),
        ...zz,
      );

    expect(digest(withEdge("1.0.0"))).not.toBe(digest(withEdge("2.0.0")));
  });

  it("follows replace = … to the entry it names, and a reference without a source that two entries share to the one without", () => {
    const replaced = (forkDependency: string) =>
      lockfile(
        entry({
          name: "app",
          version: "0.1.0",
          dependencies: ["zzlib 1.0.0 (registry+https://github.com/rust-lang/crates.io-index)"],
        }),
        entry({ name: "zzlib", version: "1.0.0", source: crates, replace: "zzlib 1.0.0" }),
        // The fork shares the name and version, without a source.
        entry({ name: "zzlib", version: "1.0.0", dependencies: [forkDependency] }),
        entry({ name: "yylib", version: "1.0.0", source: crates, checksum: "1".repeat(64) }),
        entry({ name: "yylib", version: "1.0.1", source: crates, checksum: "2".repeat(64) }),
      );

    expect(digest(replaced("yylib 1.0.0"))).not.toBe(digest(replaced("yylib 1.0.1")));
  });

  it("leaves [[patch.unused]] out", () => {
    const unused = '[[patch.unused]]\nname = "itoa"\nversion = "2.0.0"\n';

    expect(digest(lockfile(...base, unused))).toBe(digest(lockfile(...base)));
  });

  it("reads the checksums of a lockfile of the first format from its [metadata] table", () => {
    const v1 = (checksum: string) =>
      [
        entry({ name: "app", version: "0.1.0", dependencies: [`itoa 1.0.0 (${crates})`] }),
        entry({ name: "itoa", version: "1.0.0", source: crates }),
        "[metadata]",
        `"checksum itoa 1.0.0 (${crates})" = "${checksum}"`,
        "",
      ].join("\n");

    expect(digest(v1("a".repeat(64)))).not.toBe(digest(v1("b".repeat(64))));
  });

  it("fails for a member that the lockfile does not lock, and for a reference that names no entry", () => {
    expect(() => digest(lockfile(...base), { name: "absent", version: "0.1.0" })).toThrow(
      new LockfileError("it has no entry for the package absent 0.1.0"),
    );
    expect(() =>
      digest(lockfile(entry({ name: "app", version: "0.1.0", dependencies: ["missing"] }))),
    ).toThrow(/names "missing", which matches no entry/);
    expect(() => parseLockfile("not toml [")).toThrow(LockfileError);
  });
});

describe("the digest folder", () => {
  it.each([
    [".", ".nx/workspace-data/nx-rust/lockfile/%2E"],
    ["rust", ".nx/workspace-data/nx-rust/lockfile/rust"],
    ["services/billing", ".nx/workspace-data/nx-rust/lockfile/services%2Fbilling"],
    [
      "apps/Billing.API/rust_v2",
      ".nx/workspace-data/nx-rust/lockfile/apps%2FBilling.API%2Frust_v2",
    ],
    ["a b*[c]%", ".nx/workspace-data/nx-rust/lockfile/a%20b%2A%5Bc%5D%25"],
  ])("of %s is one segment without glob characters", (root, folder) => {
    expect(digestFolder(root)).toBe(folder);
  });

  it("names the workspace's project by its folder, escaped for Nx's glob matching", () => {
    expect(lockfileDependency("rust", "lockfile")).toEqual({
      projects: ["directory:rust"],
      target: "lockfile",
    });
    expect(lockfileDependency("a(b)*", "deps")).toEqual({
      projects: ["directory:a\\(b\\)\\*"],
      target: "deps",
    });
  });
});

describe("a command that excludes task dependencies", () => {
  const nx = ["/usr/bin/node", "/repo/node_modules/nx/bin/nx.js"];

  it.each([
    [["run", "a:check", "--exclude-task-dependencies"], true],
    [["run-many", "-t", "check", "--excludeTaskDependencies"], true],
    [["affected", "-t", "check", "--exclude-task-dependencies=true"], true],
    [["affected", "-t", "check", "--exclude-task-dependencies", "true"], true],
    [["run-many", "-t", "check", "--exclude-task-dependencies=false"], false],
    [["run-many", "-t", "check", "--no-exclude-task-dependencies"], false],
    [["run", "a:check"], false],
    // Words after -- go to the tasks.
    [["run", "a:run", "--", "--exclude-task-dependencies"], false],
  ])("is told from %j", (args, excludes) => {
    expect(excludesTaskDependencies([...nx, ...args])).toBe(excludes);
  });

  it("gets a command id that starts with Nx's id of its hooks and is new each time", () => {
    const first = commandRecords([...nx, "run", "a:check"], "123").NX_RUST_COMMAND_ID;
    const second = commandRecords([...nx, "run", "a:check"], "123").NX_RUST_COMMAND_ID;

    expect(first).toMatch(/^123-[0-9a-f-]{36}$/);
    expect(second).not.toBe(first);
  });

  it("gets a new run id each time, and a normal command the empty string", () => {
    const excluded = [...nx, "run", "a:check", "--exclude-task-dependencies"];
    const first = commandRecords(excluded).NX_RUST_RUN_ID;
    const second = commandRecords(excluded).NX_RUST_RUN_ID;

    expect(first).toMatch(/\S/);
    expect(second).not.toBe(first);
    expect(commandRecords([...nx, "run", "a:check"]).NX_RUST_RUN_ID).toBe("");
  });
});

describe("the digests of a run", () => {
  const member = { name: "app", version: "0.1.0" };
  let folder: string;
  let lockfilePath: string;
  const write = (lockfileText: string) => writeFileSync(lockfilePath, lockfileText);

  beforeEach(() => {
    folder = realpathSync(mkdtempSync(join(tmpdir(), "nx-rust-digests-")));
    lockfilePath = join(folder, "Cargo.lock");
    write(lockfile(...base));
  });

  afterEach(() => rmSync(folder, { recursive: true, force: true }));

  /** The workspace's digest folder and the private folder of a command. */
  const places = (command: string) => ({
    shared: join(folder, "digests"),
    own: join(folder, "digests", "commands", command),
  });

  function writeFor(command: string, now = Date.now()) {
    const { shared, own } = places(command);
    return writeDigests(
      "rust:lockfile",
      { lockfile: lockfilePath, folder: shared, commandFolder: own, members: [member] },
      now,
    );
  }

  function checkFor(command: string | undefined) {
    const { shared, own } = places(command ?? "");
    return checkDigests({
      task: "app:test",
      lockfile: lockfilePath,
      folder: shared,
      commandFolder: command === undefined ? undefined : own,
      members: [member],
      workspace: "rust",
    });
  }

  it("are written to the shared folder and to the command's own, and pass the check while all three agree", () => {
    expect(writeFor("1-a")).toBeUndefined();

    const expected = `${digest(lockfile(...base))}\n`;
    expect(readFileSync(join(places("1-a").shared, "app.digest"), "utf8")).toBe(expected);
    expect(readFileSync(join(places("1-a").own, "app.digest"), "utf8")).toBe(expected);
    expect(checkFor("1-a")).toBeUndefined();
  });

  it("fail the check when another command's lockfile task rewrote the shared digest from another lockfile", () => {
    writeFor("1-a");
    write(lockfile(...base.map((text) => text.replace("b".repeat(64), "d".repeat(64)))));
    writeFor("2-b");

    expect(checkFor("1-a")).toMatch(
      /^app:test: the locked dependencies of app had the digest \w+ when this command's lockfile task ran; now Cargo\.lock gives \w+, and the digest file that Nx hashed holds \w+\.\n[^]*another nx command that ran at the same time/,
    );
    expect(checkFor("2-b")).toBeUndefined();
  });

  it("fail the check when Cargo.lock changed alone, without a private copy, and without a command id", () => {
    writeFor("1-a");
    write(lockfile(...base.map((text) => text.replace("b".repeat(64), "d".repeat(64)))));
    expect(checkFor("1-a")).toContain("now Cargo.lock gives");

    write(lockfile(...base));
    expect(checkFor("9-z")).toContain(
      "the digest of the locked dependencies of app that this command's lockfile task wrote is missing",
    );
    expect(checkFor(undefined)).toContain("this nx command has no id");
  });

  it("keep the commands folder when stale files are removed, and remove private folders older than a day", () => {
    writeFor("1-old");
    writeFor("2-new");
    const old = places("1-old").own;
    const twoDaysAgo = (Date.now() - 2 * commandCopyLifetime) / 1000;
    utimesSync(old, twoDaysAgo, twoDaysAgo);
    writeFileSync(join(places("3").shared, "removed.digest"), "0\n");

    writeFor("3-now");

    expect(existsSync(old)).toBe(false);
    expect(existsSync(places("2-new").own)).toBe(true);
    expect(existsSync(join(places("3").shared, "removed.digest"))).toBe(false);
    expect(checkFor("3-now")).toBeUndefined();
  });

  it("of a command are removed by its postTasksExecution, in every workspace, and no other command's", () => {
    const root = folder;
    const workspaces = [
      ".nx/workspace-data/nx-rust/lockfile/rust",
      ".nx/workspace-data/nx-rust/lockfile/%2E",
    ];
    for (const workspace of workspaces) {
      for (const command of ["42-a", "42-b", "43-a"]) {
        mkdirSync(join(root, workspace, "commands", command), { recursive: true });
      }
    }

    postTasksExecution(undefined, {
      id: "42",
      workspaceRoot: root,
      nxJsonConfiguration: {},
      taskResults: {},
      argv: [],
      startTime: 0,
      endTime: 0,
    });

    for (const workspace of workspaces) {
      expect(readdirNames(join(root, workspace, "commands"))).toEqual(["43-a"]);
    }
  });
});

function readdirNames(path: string): string[] {
  return readdirSync(path).sort();
}
