import { execFileSync, spawnSync } from "node:child_process";
import {
  chmodSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  realpathSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { homedir, tmpdir } from "node:os";
import { delimiter, join } from "node:path";
import { testEnvironment } from "./environment";
import type { FileChanges } from "./fixtures";

/** The host's triple, as `rustc -vV` names it in this process's folder. */
export function testHost(): string {
  const run = spawnSync("rustc", ["-vV"], { env: testEnvironment(), encoding: "utf8" });
  const host = /^host: (\S+)$/m.exec(run.stdout ?? "")?.[1];
  if (host === undefined) {
    throw new Error(`rustc -vV names no host triple:\n${run.stdout}${run.stderr}`);
  }
  return host;
}

/**
 * The folder of a real cargo-hakari, looked up as cargo looks up a
 * subcommand: the folder that `NX_RUST_TEST_CARGO_HAKARI` names, where it
 * holds `cargo-hakari`, else the first folder on `PATH` that holds it, else
 * the `bin` of the Cargo home (`CARGO_HOME`, or `~/.cargo`); `undefined`
 * where none has it, in which case the tests that need the real tool skip
 * (`verification.mara.md`, "How the plugin is tested"). The plugin never
 * installs it (`ADR-V1-SCOPE`).
 */
export function cargoHakariFolder(): string | undefined {
  const named = process.env.NX_RUST_TEST_CARGO_HAKARI;
  const home = process.env.CARGO_HOME || join(homedir(), ".cargo");
  return [
    ...(named === undefined || named === "" ? [] : [named]),
    ...(process.env.PATH ?? "").split(delimiter),
    join(home, "bin"),
  ].find((folder) => folder !== "" && existsSync(join(folder, "cargo-hakari")));
}

/**
 * A folder with a `cargo-hakari` that prints its arguments and succeeds, for
 * the tests whose point is not the drift check: the crates' cached tasks
 * depend on `hakari-check`, which then passes without the real tool.
 */
export class StubHakari {
  readonly folder = mkdtempSync(join(tmpdir(), "nx-rust-hakari-"));

  constructor() {
    const file = join(this.folder, "cargo-hakari");
    writeFileSync(file, '#!/bin/sh\necho "stub cargo-hakari $*"\n');
    chmodSync(file, 0o755);
  }

  remove(): void {
    rmSync(this.folder, { recursive: true, force: true });
  }
}

/** `PATH` with `folder` in front, for an Nx command whose tasks run cargo-hakari from there. */
export function pathWith(folder: string): string {
  return [folder, testEnvironment().PATH ?? ""].join(delimiter);
}

/**
 * `.config/hakari.toml` as `cargo hakari init` writes it, without its
 * comments, with `platforms` set and the lines in `extra` added.
 */
export function hakariConfiguration(
  hackPackage: string,
  platforms: readonly string[],
  extra: readonly string[] = [],
): string {
  return [
    `hakari-package = "${hackPackage}"`,
    'dep-format-version = "4"',
    'resolver = "2"',
    `platforms = [${platforms.map((triple) => JSON.stringify(triple)).join(", ")}]`,
    ...extra,
    "",
  ].join("\n");
}

/**
 * The files of a hack crate named `name` in `folder`, as cargo-hakari 0.9.39
 * generates it, whose hakari section holds `dependencies`, one line each, such
 * as `x = { git = "file:///…", default-features = false, features = ["f1"] }`.
 */
export function hackCrateFiles(
  folder: string,
  name: string,
  dependencies: readonly string[] = [],
): FileChanges {
  return {
    [`${folder}/Cargo.toml`]: [
      "# This file is generated by `cargo hakari`.",
      "# To regenerate, run:",
      "#     cargo hakari generate",
      "",
      "[package]",
      `name = "${name}"`,
      'version = "0.1.0"',
      'edition = "2021"',
      'description = "workspace-hack package, managed by hakari"',
      "# You can choose to publish this crate: see https://docs.rs/cargo-hakari/latest/cargo_hakari/publishing.",
      "publish = false",
      "",
      "# The parts of the file between the BEGIN HAKARI SECTION and END HAKARI SECTION comments",
      "# are managed by hakari.",
      "",
      "### BEGIN HAKARI SECTION",
      ...(dependencies.length === 0 ? [] : ["[dependencies]", ...dependencies, ""]),
      "### END HAKARI SECTION",
      "",
    ].join("\n"),
    [`${folder}/build.rs`]:
      "// A build script is required for cargo to consider build dependencies.\nfn main() {}\n",
    [`${folder}/src/lib.rs`]: "// This is a stub lib.rs.\n",
  };
}

/** A git repository that holds the third-party crate of the hakari tests. */
export interface ThirdPartyRepository {
  /** Its `file://` URL, which manifests name in a `git` key. */
  url: string;
  remove(): void;
}

/**
 * A git repository with the crate `name`, `x` by default, whose features `f1`, `f2` and `f3`
 * turn on nothing but themselves and whose function `features()` names those
 * that are on, such as `f1 f2`: a third-party crate that cargo-hakari unifies,
 * without a registry.
 */
export function thirdPartyRepository(name = "x"): ThirdPartyRepository {
  const folder = realpathSync(mkdtempSync(join(tmpdir(), `nx-rust-${name}-`)));
  mkdirSync(join(folder, "src"));
  writeFileSync(
    join(folder, "Cargo.toml"),
    `[package]\nname = "${name}"\nversion = "0.1.0"\nedition = "2021"\n\n[features]\nf1 = []\nf2 = []\nf3 = []\n`,
  );
  writeFileSync(
    join(folder, "src", "lib.rs"),
    [
      "pub fn features() -> String {",
      "    let mut on = Vec::new();",
      '    if cfg!(feature = "f1") {',
      '        on.push("f1");',
      "    }",
      '    if cfg!(feature = "f2") {',
      '        on.push("f2");',
      "    }",
      '    if cfg!(feature = "f3") {',
      '        on.push("f3");',
      "    }",
      '    if on.is_empty() { "none".to_string() } else { on.join(" ") }',
      "}",
      "",
    ].join("\n"),
  );
  const git = (...args: string[]) =>
    execFileSync(
      "git",
      ["-c", "user.name=t", "-c", "user.email=t@t", "-c", "commit.gpgsign=false", ...args],
      { cwd: folder, env: testEnvironment(), stdio: "pipe" },
    );
  git("init", "-q");
  git("add", "-A");
  git("commit", "-q", "-m", "x");
  return {
    url: `file://${folder}`,
    remove: () => rmSync(folder, { recursive: true, force: true }),
  };
}

/**
 * The files of a Cargo workspace in `root` that uses `hakari` and passes
 * every check of `DES-UNIFICATION`: the binary `a` asks `x` for `f1`, `b`
 * asks it for `f2` and and
 * each depends on the hack crate `workspace-hack`, whose hakari section asks
 * `x` for both, with `platforms` naming `host`. `a`'s binary prints the
 * features of `x` that it was compiled with; `b` is a library with a test
 * that does the same. Run `cargo generate-lockfile` before Nx.
 */
export function hakariWorkspace(
  root: string,
  repository: ThirdPartyRepository,
  host: string,
): FileChanges {
  const crate = (name: string, kind: "bin" | "lib", feature: string) => ({
    [`${root}/${name}/Cargo.toml`]: [
      "[package]",
      `name = "${name}"`,
      'version = "0.1.0"',
      'edition = "2024"',
      "",
      "[dependencies]",
      `x = { git = "${repository.url}", features = ["${feature}"] }`,
      'workspace-hack = { version = "0.1", path = "../workspace-hack" }',
      "",
    ].join("\n"),
    ...(kind === "bin"
      ? { [`${root}/${name}/src/main.rs`]: 'fn main() {\n    println!("{}", x::features());\n}\n' }
      : {
          [`${root}/${name}/src/lib.rs`]:
            'pub fn features() -> String {\n    x::features()\n}\n\n#[cfg(test)]\nmod tests {\n    #[test]\n    fn prints() {\n        println!("features: {}", super::features());\n    }\n}\n',
        }),
  });
  return {
    [`${root}/Cargo.toml`]: '[workspace]\nmembers = ["a", "b", "workspace-hack"]\nresolver = "2"\n',
    [`${root}/.config/hakari.toml`]: hakariConfiguration("workspace-hack", [host]),
    ...crate("a", "bin", "f1"),
    ...crate("b", "lib", "f2"),
    ...hackCrateFiles(`${root}/workspace-hack`, "workspace-hack", [
      `x = { git = "${repository.url}", default-features = false, features = ["f1", "f2"] }`,
    ]),
  };
}

/** `changes` laid over `base`: a function receives the file as `base` writes it. */
export function composed(base: FileChanges, changes: FileChanges): FileChanges {
  const result: FileChanges = { ...base };
  for (const [file, change] of Object.entries(changes)) {
    const before = result[file];
    result[file] =
      typeof change === "function" && typeof before === "string" ? change(before) : change;
  }
  return result;
}

/**
 * The files that make the Cargo workspace in `root` use `hakari` at graph
 * creation: `.config/hakari.toml` with the host's triple in `platforms`,
 * naming the hack crate `hack` in `folder` below `root`, which the
 * workspace's `members` must cover, with an empty hakari section. Members
 * need no dependency on it for graph creation; the drift check, which the
 * key tests do not run, would ask for one.
 */
export function hakariSetup(root: string, folder = "crates/hack", host = testHost()): FileChanges {
  const prefix = root === "." ? "" : `${root}/`;
  return {
    [`${prefix}.config/hakari.toml`]: hakariConfiguration("hack", [host]),
    ...hackCrateFiles(`${prefix}${folder}`, "hack"),
  };
}
